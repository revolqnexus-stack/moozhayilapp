# Builds apps/api/.env.cloud from PRODUCTION_ENV.txt for local dev against Neon + Upstash.
# Usage: powershell -ExecutionPolicy Bypass -File scripts/sync-cloud-env.ps1

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$Source = Join-Path $Root "PRODUCTION_ENV.txt"
$Target = Join-Path $Root "apps\api\.env.cloud"

if (-not (Test-Path $Source)) {
  Write-Error "Missing $Source - copy secrets from Neon/Upstash dashboards first."
}

$lines = Get-Content $Source | Where-Object {
  $_ -match '^\s*[A-Z_][A-Z0-9_]*=' -and $_ -notmatch '^\s*#'
}

$overrides = [ordered]@{
  "NODE_ENV" = "staging"
  "PORT" = "3080"
  "TRUST_PROXY" = "false"
  "PUBLIC_BASE_URL" = "http://localhost:3080"
  "CORS_ALLOWED_ORIGINS" = "http://localhost:5180,http://localhost:5173,http://localhost:3080,http://10.0.2.2:3080"
  "STORAGE_BACKEND" = "local"
  "SMS_PROVIDER_MODE" = "mock"
  "KYC_PROVIDER_MODE" = "mock"
  "FIREBASE_MODE" = "mock"
  "PAYMENT_PROVIDER_MODE" = "mock"
  "ENABLE_DEMO_SEEDS" = "false"
}

$map = @{}
foreach ($line in $lines) {
  $idx = $line.IndexOf("=")
  if ($idx -lt 1) { continue }
  $key = $line.Substring(0, $idx).Trim()
  $val = $line.Substring($idx + 1).Trim()
  $map[$key] = $val
}

foreach ($entry in $overrides.GetEnumerator()) {
  $map[$entry.Key] = $entry.Value
}

$header = @(
  "# Auto-generated by scripts/sync-cloud-env.ps1 - do not commit",
  "# Local API -> Neon PostgreSQL + Upstash Redis (staging mode)",
  ""
)

$body = $map.GetEnumerator() | Sort-Object Name | ForEach-Object {
  "{0}={1}" -f $_.Key, $_.Value
}

Set-Content -Path $Target -Value ($header + $body) -Encoding UTF8
Write-Host "Wrote $Target"
Write-Host "Run from apps/api: npm run dev:cloud"
